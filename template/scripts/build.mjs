// Builds the static site into dist/, writes /.well-known/greenhouse.json (Greenhouse package
// contract) and publishes the user guide for agents: a Markdown copy of every docs page
// (/docs/<page>.md), /llms.txt (the index) and /llms-full.txt (the whole guide). No dependencies.
import { appendFileSync, cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const src = join(root, "site");
const out = join(root, "dist");

// The slug comes from greenhouse.yaml so it is set in one place.
const slug = /^slug:\s*([a-z0-9][a-z0-9-]*)\s*$/m.exec(readFileSync(join(root, "greenhouse.yaml"), "utf8"))?.[1];
if (!slug) throw new Error("greenhouse.yaml has no slug");

// Cloudflare Pages sets CF_PAGES_COMMIT_SHA; elsewhere use the checkout's HEAD.
function commitSha() {
  if (process.env.CF_PAGES_COMMIT_SHA) return process.env.CF_PAGES_COMMIT_SHA;
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
  } catch {
    throw new Error("No commit SHA: set CF_PAGES_COMMIT_SHA or build inside a git checkout");
  }
}

const sha = commitSha();
if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error(`Not a full commit SHA: ${sha}`);

rmSync(out, { recursive: true, force: true });
cpSync(src, out, { recursive: true });
mkdirSync(join(out, ".well-known"), { recursive: true });
const info = { slug, sha, built_at: new Date().toISOString() };
writeFileSync(join(out, ".well-known", "greenhouse.json"), JSON.stringify(info, null, 2) + "\n");

// ---- User guide for agents (decision 0006) ----
// The docs pages are the ones greenhouse.yaml's docs: block names, in guide order.
const manifest = readFileSync(join(root, "greenhouse.yaml"), "utf8");
const docsBlock = /^docs:\n((?:[ \t]+.*\n?)+)/m.exec(manifest)?.[1] ?? "";
const docPaths = [...new Set([...docsBlock.matchAll(/^\s+[a-z_]+:\s*(\/[^\s#]*)/gm)].map((m) => m[1]))];

const decode = (s) =>
  s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16))).replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d))).replace(/&middot;/g, "·").replace(/&amp;/g, "&");
const inline = (s) =>
  decode(
    s
      .replace(/<code>([\s\S]*?)<\/code>/g, (_, c) => "`" + c + "`")
      .replace(/<a\b[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g, (_, h, t) => `[${t}](${h})`)
      .replace(/<[^>]+>/g, "")
      .replace(/\s+/g, " ")
      .trim(),
  );

/** The page's <main> as Markdown: headings (with their ids), paragraphs, lists, code, figures. */
function toMarkdown(html) {
  const main = /<main>([\s\S]*?)<\/main>/.exec(html)?.[1] ?? "";
  const out = [];
  const re = /<h([1-3])(?:\s+id="([^"]*)")?[^>]*>([\s\S]*?)<\/h\1>|<p>([\s\S]*?)<\/p>|<pre><code[^>]*>([\s\S]*?)<\/code><\/pre>|<ul>([\s\S]*?)<\/ul>|<figure>[\s\S]*?aria-label="([^"]*)"[\s\S]*?<\/figure>/g;
  for (const m of main.matchAll(re)) {
    if (m[1]) out.push(`${"#".repeat(Number(m[1]))} ${inline(m[3])}${m[2] ? ` {#${m[2]}}` : ""}`);
    else if (m[4] !== undefined) {
      if (/All docs/.test(m[4])) continue; // the page footer links
      out.push(inline(m[4]));
    } else if (m[5] !== undefined) out.push("```\n" + decode(m[5]) + "\n```");
    else if (m[6] !== undefined) out.push([...m[6].matchAll(/<li>([\s\S]*?)<\/li>/g)].map((li) => `- ${inline(li[1])}`).join("\n"));
    else if (m[7] !== undefined) out.push(`> ${decode(m[7])}`);
  }
  return out.join("\n\n") + "\n";
}

const pages = [];
for (const p of docPaths) {
  const html = readFileSync(join(out, p, "index.html"), "utf8");
  const title = inline(/<h1[^>]*>([\s\S]*?)<\/h1>/.exec(html)?.[1] ?? p);
  const description = decode(/<meta name="description" content="([^"]*)"/.exec(html)?.[1] ?? "");
  const mdPath = `${p.replace(/\/$/, "")}.md`;
  const md = toMarkdown(html);
  writeFileSync(join(out, mdPath), md);
  pages.push({ path: p, mdPath, title, description, md });
}
writeFileSync(
  join(out, "llms.txt"),
  `# Example Seed\n\n> A project registry with an HTTP API: name a project once, and every tool reads the same record.\n\n## User guide\n\n` +
    pages.map((g) => `- [${g.title}](${g.mdPath}): ${g.description}`).join("\n") +
    `\n\n## Optional\n\n- [The whole guide in one file](/llms-full.txt)\n`,
);
writeFileSync(join(out, "llms-full.txt"), pages.map((g) => `Source: ${g.path} (Markdown: ${g.mdPath})\n\n${g.md}`).join("\n---\n\n"));
appendFileSync(
  join(out, "_headers"),
  "\n# Generated by scripts/build.mjs: the guide's Markdown and llms files.\n" +
    [...pages.map((g) => g.mdPath), "/llms.txt", "/llms-full.txt"]
      .map((f) => `${f}\n  Content-Type: ${f.endsWith(".md") ? "text/markdown" : "text/plain"}; charset=utf-8\n`)
      .join("\n"),
);

console.log(`dist/ built for ${slug} at ${sha}: ${pages.length} guide pages with Markdown, llms.txt and llms-full.txt`);
